#!/usr/bin/env python3
"""DRBR: src/Drbr.Core/BuildInfo.g.cs from drbr.json (versions, the GitHub update URL, the public signing key).
Usage: python3 packaging/gen_buildinfo.py [--owner OWNER --repo REPO]"""
import json, os, sys, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def cs(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--owner')
    ap.add_argument('--repo')
    a = ap.parse_args()
    cfg = json.load(open(os.path.join(ROOT, 'drbr.json')))
    owner = a.owner or os.environ.get('DRBR_GH_OWNER') or cfg['github']['owner']
    repo = a.repo or os.environ.get('DRBR_GH_REPO') or cfg['github']['repo']
    url = cfg['update_manifest_url'].replace('{owner}', owner).replace('{repo}', repo)
    configured = owner != 'OWNER'
    sp = cfg['save_profile']
    out = '''// GENERATED by packaging/gen_buildinfo.py from drbr.json - do not edit by hand.
namespace Drbr
{
    public static class BuildInfo
    {
        public const string Product = "DRBR";
        public const string Title = %s;
        public const string Version = %s;
        public const string ModBuild = %s;
        public const int Protocol = %d;
        public const string GitHubOwner = %s;
        public const string GitHubRepo = %s;
        public const bool UpdatesConfigured = %s;
        public const string UpdateManifestUrl = %s;
        public const string PublicKeyModulus = %s;
        public const string PublicKeyExponent = %s;
        public const int SaveSchemaVersion = %d;
        public const int SaveTemplateVersion = %d;
        public const int SaveMigrationVersion = %d;
        public const string StartingLocation = %s;
        public const int StartingRoomId = %d;
        public const int StartingPlot = %d;
        public const string DefaultStartMode = %s;
    }
}
''' % (cs(cfg['title']), cs(cfg['launcher_version']), cs(cfg['mod_build']), int(cfg['protocol']), cs(owner), cs(repo),
       'true' if configured else 'false', cs(url), cs(cfg['public_key']['modulus_b64']), cs(cfg['public_key']['exponent_b64']),
       sp['schema_version'], sp['save_template_version'], sp['migration_version'], cs(sp['starting_location']), sp['starting_room_id'],
       sp['starting_plot'], cs(sp['default_start_mode']))
    p = os.path.join(ROOT, 'src', 'Drbr.Core', 'BuildInfo.g.cs')
    open(p, 'w').write(out)
    print('wrote', p, '(updates %s: %s)' % ('configured' if configured else 'NOT configured - no GitHub owner yet', url))


if __name__ == '__main__':
    main()
